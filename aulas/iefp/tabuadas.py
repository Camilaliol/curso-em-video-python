print(f"                                                                    Tabuada do numero 1 ate 10                                                                  |")
print("|---------------------------------------------------------------------------------------------------------------------------------------------------------------|")

for tabuada in range(1,11):
    print("|", end="")
    
    for numero in range (1,11):
        resultado = tabuada * numero
        print(f"{tabuada} * {numero} = {resultado}",end="\t")
        print("|",end="")
    print()
      
